/**
 * emit-product-images.mjs — collects the images each product page already
 * carries into data/product-images.js, for the location sections to reuse.
 *
 * No new artwork: the location sections show the same four pictures the master
 * product page has always shown, with the same alt text. Every product page
 * happens to carry exactly five — a hero backdrop plus four product shots —
 * so the backdrop is dropped and the remaining four are rotated by one, which
 * keeps the introduction section's picture from reappearing directly beneath
 * itself.
 *
 * Run: node scripts/emit-product-images.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { PRODUCTS } from '../data/locations.js';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const TEMPLATES = join(ROOT, 'components', 'templates', 'products');

const pascal = (slug) =>
  slug.split('-').map((w) => w[0].toUpperCase() + w.slice(1)).join('');

const out = {};

for (const product of PRODUCTS) {
  const file = join(TEMPLATES, pascal(product.slug) + 'Template.jsx');
  const src = readFileSync(file, 'utf8');

  /* <img alt={"…"} src={"…"} /> — the order the page renders them in. */
  const found = [];
  const seen = new Set();
  for (const m of src.matchAll(/<img[^>]*?alt=\{"([^"]*)"\}[^>]*?src=\{"([^"]*)"\}/g)) {
    const [, alt, source] = m;
    if (source.includes('logo') || seen.has(source)) continue;
    seen.add(source);
    found.push({ src: source, alt });
  }

  if (found.length < 5) {
    console.error(product.slug + ': expected 5 images, found ' + found.length);
    process.exit(1);
  }

  /* Drop the hero backdrop, then rotate so the introduction image lands last. */
  const content = found.slice(1, 5);
  out[product.slug] = [...content.slice(1), content[0]];
}

const q = (s) => JSON.stringify(s);
let body = '';
for (const [slug, images] of Object.entries(out)) {
  body += '  ' + q(slug) + ': [\n';
  for (const image of images) {
    body += '    { src: ' + q(image.src) + ', alt: ' + q(image.alt) + ' },\n';
  }
  body += '  ],\n';
}

const file = `/**
 * The four pictures each product page lends to its location sections, in
 * Manufacturer / Supplier / Exporter / Wholesaler order.
 *
 * These are the master page's own images and its own alt text — nothing new was
 * added and nothing is location-specific, so every location shows the same
 * four pictures for a given product, exactly as the brief requires.
 *
 * Generated by scripts/emit-product-images.mjs.
 */

export const PRODUCT_IMAGES = {
${body}};
`;

writeFileSync(join(ROOT, 'data', 'product-images.js'), file, 'utf8');
console.log('wrote data/product-images.js');
for (const [slug, images] of Object.entries(out)) {
  console.log('  ' + slug.padEnd(30) + images.map((i) => i.src.replace('/img/', '')).join(', '));
}
